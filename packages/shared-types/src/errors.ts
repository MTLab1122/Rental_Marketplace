/**
 * Standard System Error Codes
 */
export enum ErrorCode {
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  UNAUTHORIZED = 'UNAUTHORIZED',
  FORBIDDEN = 'FORBIDDEN',
  NOT_FOUND = 'NOT_FOUND',
  CONFLICT = 'CONFLICT',
  RATE_LIMIT_EXCEEDED = 'RATE_LIMIT_EXCEEDED',
  OUTSIDE_SERVICE_BOUNDARY = 'OUTSIDE_SERVICE_BOUNDARY',
  LOCATION_OUTSIDE_PESHAWAR = 'LOCATION_OUTSIDE_PESHAWAR',
  INVALID_ELIGIBILITY = 'INVALID_ELIGIBILITY',
  INVALID_ELIGIBILITY_PROPERTY_TYPE = 'INVALID_ELIGIBILITY_PROPERTY_TYPE',
  LOCALITY_INACTIVE = 'LOCALITY_INACTIVE',
  IMAGE_REQUIRED_FOR_REVIEW = 'IMAGE_REQUIRED_FOR_REVIEW',
  INVALID_STATUS_TRANSITION = 'INVALID_STATUS_TRANSITION',
  INTERNAL_SERVER_ERROR = 'INTERNAL_SERVER_ERROR',
  SERVICE_UNAVAILABLE = 'SERVICE_UNAVAILABLE',
}

export interface ApiErrorDetail {
  field?: string;
  message: string;
  code?: string;
}

export interface ApiErrorPayload {
  code: ErrorCode | string;
  message: string;
  details?: ApiErrorDetail[];
  requestId?: string;
  timestamp?: string;
}
